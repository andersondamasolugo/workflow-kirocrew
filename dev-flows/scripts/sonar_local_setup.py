#!/usr/bin/env python3
"""(Re)create local SonarQube configs for a repo, from its SonarCloud configs.

For every sonar-project.properties in the repo root or one level below
(frontend root, or each *-ms module of a backend monorepo) it writes a sibling
sonar-local.properties: same analysis settings, local identity and host, and a
separate working directory. Both files are added to .git/info/exclude, so
nothing ever reaches GitHub. Safe to run again: files are regenerated.

Usage:
    sonar_local_setup.py <repo_dir>
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

SOURCE = "sonar-project.properties"
TARGET = "sonar-local.properties"
HOST = "http://localhost:9000"
CLOUD_ONLY_KEYS = ("sonar.projectKey", "sonar.projectName", "sonar.organization", "sonar.host.url")
EXCLUDES = (TARGET, ".scannerwork-local/")


def local_config(source: Path, project_key: str) -> str:
    """Build the local config text from a SonarCloud config file."""
    kept = [
        line for line in source.read_text(encoding="utf-8").splitlines()
        if not line.strip().startswith(tuple(f"{key}=" for key in CLOUD_ONLY_KEYS))
        and line.strip() != "# Required metadata"
    ]
    header = [
        "# Local SonarQube config. Generated by sonar_local_setup.py from "
        f"{SOURCE}. Not committed.",
        f"sonar.projectKey={project_key}",
        f"sonar.projectName={project_key.removesuffix('-local')} (local)",
        f"sonar.host.url={HOST}",
        "# .scannerwork may be tracked in git: keep local analysis files apart",
        "sonar.working.directory=.scannerwork-local",
        "",
    ]
    return "\n".join(header + kept) + "\n"


def add_git_excludes(repo: Path) -> None:
    """Append the local-only patterns to .git/info/exclude when missing."""
    git_dir = subprocess.run(["git", "rev-parse", "--git-dir"], cwd=repo,
                             capture_output=True, text=True, check=True).stdout.strip()
    exclude = (repo / git_dir / "info" / "exclude").resolve()
    exclude.parent.mkdir(parents=True, exist_ok=True)
    current = exclude.read_text(encoding="utf-8").splitlines() if exclude.exists() else []
    missing = [pattern for pattern in EXCLUDES if pattern not in current]
    if missing:
        with exclude.open("a", encoding="utf-8") as handle:
            handle.write("\n".join(missing) + "\n")


def main() -> None:
    """Entry point: generate every local config of the repo and report them."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("repo")
    repo = Path(parser.parse_args().repo).expanduser().resolve()
    sources = sorted([*repo.glob(SOURCE), *repo.glob(f"*/{SOURCE}")])
    if not sources:
        sys.exit(f"no {SOURCE} found in {repo} or its first-level folders")

    for source in sources:
        module = source.parent
        suffix = "" if module == repo else f"-{module.name}"
        project_key = f"{repo.name}{suffix}-local"
        (module / TARGET).write_text(local_config(source, project_key), encoding="utf-8")
        print(f"ok  {module.relative_to(repo.parent)}/{TARGET}  ({project_key})")
    add_git_excludes(repo)
    print(f"git exclude: {', '.join(EXCLUDES)}")


if __name__ == "__main__":
    main()
